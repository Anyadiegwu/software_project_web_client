// ── Helper: derive initials from officer object ──
const getInitials = (officer) => {
  if (!officer) return "?";
  if (officer.initials) return officer.initials;
  const name = officer.name || officer.fullName || "";
  const parts = name.trim().split(" ");
  if (parts.length >= 2) return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
  if (parts[0]) return parts[0][0].toUpperCase();
  return "?";
};

// ── Helper: derive display name ──
const getDisplayName = (officer) => {
  if (!officer) return "Officer";
  return officer.name || officer.fullName || `${officer.firstName || ""} ${officer.lastName || ""}`.trim() || "Officer";
};

